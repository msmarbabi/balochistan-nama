// ============================================

export interface MoonPhaseInfo {
  name: string;
  emoji: string;
  illumination: number;
  phase: number;
}

export function getMoonPhase(date: Date): MoonPhaseInfo {
  // Reference: Known new moon on January 6, 2000 18:14 UTC
  const knownNewMoon = new Date(Date.UTC(2000, 0, 6, 18, 14, 0)).getTime();
  const synodicMonth = 29.53058867; // days

  const diffDays = (date.getTime() - knownNewMoon) / (1000 * 60 * 60 * 24);
  const phase = ((diffDays % synodicMonth) + synodicMonth) % synodicMonth;
  const phaseRatio = phase / synodicMonth;

  // Illumination: 0 at new moon, 1 at full moon
  let illumination: number;
  if (phaseRatio <= 0.5) {
    illumination = phaseRatio * 2;
  } else {
    illumination = (1 - phaseRatio) * 2;
  }
  illumination = Math.round(illumination * 100) / 100;

  let name: string;
  let emoji: string;

  if (phaseRatio < 0.025) {
    name = 'ماه نو (رأس‌القمر)';
    emoji = '🌑';
  } else if (phaseRatio < 0.225) {
    name = 'هلال اول';
    emoji = '🌒';
  } else if (phaseRatio < 0.275) {
    name = 'ربع اول';
    emoji = '🌓';
  } else if (phaseRatio < 0.475) {
    name = 'بدر متوسط (ماه نیمه‌درخشان)';
    emoji = '🌔';
  } else if (phaseRatio < 0.525) {
    name = 'بدر کامل (ماه کامل)';
    emoji = '🌕';
  } else if (phaseRatio < 0.725) {
    name = 'ماه کاهشی (بدر نزولی)';
    emoji = '🌖';
  } else if (phaseRatio < 0.775) {
    name = 'ربع آخر';
    emoji = '🌗';
  } else if (phaseRatio < 0.975) {
    name = 'هلال آخر';
    emoji = '🌘';
  } else {
    name = 'ماه نو (رأس‌القمر)';
    emoji = '🌑';
  }

  return {
    name,
    emoji,
    illumination,
    phase: Math.round(phase * 10) / 10,
  };
}