// ============================================
// Daily Poem Selector
// ============================================

/**
 * دریافت شعر روز بر اساس روز سال
 * Get a poem for the day, cycling through the collection
 *
 * @param dayOfYear - روز سال (۱ تا ۳۶۶)
 */
export function getDailyPoem(dayOfYear: number): Poem {
  const index = (dayOfYear - 1) % poems.length;
  return poems[index];
}

/**
 * دریافت شعر‌های بر اساس نوع
 * Get poems filtered by type
 */
export function getPoemsByType(type: Poem['type']): Poem[] {
  return poems.filter((p) => p.type === type);
}

/**
 * دریافت شعر‌های یک شاعر
 * Get poems by a specific poet
 */
export function getPoemsByPoet(poetName: string): Poem[] {
  return poems.filter((p) => p.poet === poetName);
}

/**
 * دریافت شعر تصادفی
 * Get a random poem
 */
export function getRandomPoem(): Poem {
  const index = Math.floor(Math.random() * poems.length);
  return poems[index];
}
