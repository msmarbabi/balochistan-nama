  // Random pick helper
  function pick(arr, seed) {
    if (typeof seed === 'number') {
      const idx = Math.floor(Math.abs(Math.sin(seed) * 1000000)) % arr.length;
      return arr[idx];
    }
    return arr[Math.floor(Math.random() * arr.length)];
  }

